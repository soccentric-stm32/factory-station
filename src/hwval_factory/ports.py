"""Typing ports for the station adapters (P1-01).

A step may depend on these structural types, never on a concrete OpenOCD,
pyserial or SQLite implementation.  The real and simulated adapters already
satisfy them; the protocols exist so a new transport cannot silently change
the step contract.
"""

from __future__ import annotations

from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class SwdPort(Protocol):
    def start(self) -> None: ...
    def stop(self) -> None: ...
    def command(self, command: str, timeout: float = 20.0) -> str: ...
    def halt(self) -> None: ...
    def reset(self, halt: bool = False) -> None: ...
    def mass_erase(self) -> None: ...
    def program(self, path: Any, address: int | None = None, verify: bool = True) -> None: ...
    def verify_image(self, path: Any, address: int | None = None) -> None: ...
    def read_u32(self, address: int) -> int: ...
    def read_u16(self, address: int) -> int: ...
    def read_memory(self, address: int, length: int) -> bytes: ...
    def write_memory(self, address: int, data: bytes) -> None: ...
    def erase_address(self, address: int, length: int) -> None: ...
    def read_option_bytes(self) -> Any: ...
    def write_option_bytes(self, optcr: int, optcr1: int) -> None: ...
    def unlock_rdp(self) -> None: ...


@runtime_checkable
class LinkPort(Protocol):
    link_log: list[str]

    def close(self) -> None: ...
    def hello(self, timeout: float | None = None) -> dict[str, Any]: ...
    def connect(self, expected_role: str | int | None = None, **kwargs: Any) -> dict[str, Any]: ...
    def request(self, payload: bytes, **kwargs: Any) -> Any: ...
    def status(self) -> dict[str, Any]: ...
    def boot_info(self) -> dict[str, Any]: ...
    def reset(self) -> None: ...
    def update_image(self, image: Any, **kwargs: Any) -> dict[str, Any]: ...


@runtime_checkable
class PowerPort(Protocol):
    def on(self) -> None: ...
    def off(self) -> None: ...
    def close(self) -> None: ...


@runtime_checkable
class ScannerPort(Protocol):
    def submit_scan(self, text: str, fixture: str | None = None) -> str | None: ...
    def waiting_fixtures(self) -> list[str]: ...


@runtime_checkable
class PrinterPort(Protocol):
    def reprint(self, run_id: int, **kwargs: Any) -> Any: ...
    def print_label(self, *args: Any, **kwargs: Any) -> Any: ...


@runtime_checkable
class MesPort(Protocol):
    def queue(self, run_id: int) -> None: ...
    def flush(self) -> Any: ...


@runtime_checkable
class StorePort(Protocol):
    def run(self, run_id: int) -> Any: ...
    def steps(self, run_id: int) -> Any: ...
    def tests(self, run_id: int) -> Any: ...
    def audit(self, user: str, action: str, detail: str = "") -> None: ...


@runtime_checkable
class DebugLogPort(Protocol):
    def start(self) -> None: ...
    def stop(self) -> list[str]: ...
    def lines(self) -> list[str]: ...


@runtime_checkable
class ClockPort(Protocol):
    def monotonic(self) -> float: ...
    def sleep(self, seconds: float) -> None: ...


@runtime_checkable
class OperatorPort(Protocol):
    def prompt(self, prompt: dict[str, Any]) -> str: ...
    def confirm(self, question: str) -> bool: ...


__all__ = [
    "ClockPort",
    "DebugLogPort",
    "LinkPort",
    "MesPort",
    "OperatorPort",
    "PowerPort",
    "PrinterPort",
    "ScannerPort",
    "StorePort",
    "SwdPort",
]
